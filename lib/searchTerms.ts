/* 표기 → 그 묶음 전체. 한 표기가 두 묶음에 들어가면 둘 다 합쳐 준다.
 *
 * **한 글자 표기는 넣지 못하게 막는다.** 판정이 `kw.includes(표기)` 라 한 글자는 어디에나
 * 걸린다 — '노트북 → 북' 을 넣었더니 '북' 이 든 모든 항목이 노트북으로 잡혔다. */
const EXPAND = new Map<string, string[]>()
for (const g of SYNONYM_GROUPS) {
  for (const w of g) {
    if (w.length < 2) throw new Error(`동의어 표기가 한 글자입니다: "${w}" — 어디에나 걸립니다`)
    const cur = EXPAND.get(w) || []
    EXPAND.set(w, Array.from(new Set(cur.concat(g))))
  }
}

/*
 * 단위 표기가 갈리는 것들 — 65형과 65인치는 같은 말이다(화면은 인치로 적는다).
 *
 * **단위를 뗀 맨숫자는 넣지 않는다.** 한때 '20kg' → '20' 까지 넣었더니 20이 든 값이면
 * 무엇이든 걸려 **567건**이 나왔다(제대로는 39건). 조건을 겹쳐 좁히는 도구에서 조건 하나가
 * 아무거나 무는 것은 없느니만 못하다. 맨숫자로 찾고 싶으면 맨숫자로 치면 된다.
 */
const UNIT_PAIRS: [RegExp, (n: string) => string[]][] = [
  [/^(\d+)(인치|형)$/, (n) => [`${n}인치`, `${n}형`]],
  [/^(\d+)(리터|l)$/i, (n) => [`${n}리터`, `${n}l`]],
  [/^(\d+)(kg|킬로|키로)$/i, (n) => [`${n}kg`]],
  [/^(\d+)(mm|밀리)$/i, (n) => [`${n}mm`]],
]

/* 뒤에 붙는 조사를 떼어 본다. 떼어낸 형태를 **추가**할 뿐 원형을 버리지 않으므로
 * 이 규칙 때문에 걸리던 것이 안 걸리는 일은 없다. 두 글자 이하로 줄면 떼지 않는다
 * ('세로'→'세', '경로'→'경' 처럼 뜻이 없는 조각이 되기 때문). */
const PARTICLES = ['은', '는', '이', '가', '을', '를', '의', '에', '도', '만', '로',
  '야', '요', '죠', '서', '랑', '과', '와', '나']

/**
 * 색인·질의 양쪽에 같이 거는 정규화.
 * 숫자 안의 쉼표(912×1,853)와 곱셈기호를 없애 "1853"으로도 찾을 수 있게 한다.
 */
export function normalize(s: string): string {
  return String(s || '')
    .toLowerCase()
    .replace(/(\d),(?=\d)/g, '$1')
    .replace(/[×✕х]/g, 'x')
    .replace(/\s+/g, ' ')
    .trim()
}

/** 토큰 하나가 걸릴 수 있는 표기 전부. 이 중 **하나라도** 맞으면 그 조건은 충족이다. */
export function expandToken(tokenRaw: string): string[] {
  const t = normalize(tokenRaw)
  if (!t) return []
  const out = new Set<string>([t])

  for (const [re, make] of UNIT_PAIRS) {
    const m = t.match(re)
    if (m) for (const v of make(m[1])) out.add(v)
  }

  for (const p of PARTICLES) {
    if (t.length >= 3 && t.endsWith(p)) out.add(t.slice(0, -1))
  }

  // 동의어는 위에서 만들어진 변형들에도 걸어 준다("식세기는" → "식세기" → "식기세척기")
  for (const v of Array.from(out)) {
    for (const w of EXPAND.get(v) || []) out.add(normalize(w))
  }
  return Array.from(out)
}

/*
 * **자연어로 물어도 걸려야 한다**(2026-08-11 사용자 요청: *"통합검색은 말 그대로 세일즈
 * 코파일럿 내 모든 정보를 자연어로 검색하게 해줘야 합니다"*).
 *
 * 사람은 "냉장고 컴프레서 몇 년이야" 처럼 묻는데, 조건이 AND 라 '몇' 이 0건이면
 * **문장 전체가 0건**이 된다. 그래서 뜻을 담지 않는 말은 조건에서 뺀다.
 *
 * 빼는 것은 **결과를 넓히기만 한다** — 조건이 줄어드는 방향이라 있던 결과가 사라지지 않는다.
 * 대신 **무엇을 뺐는지 화면에 밝힌다**(`ignoredWords`). 조용히 빼면 "왜 이게 나오지"가 된다.
 */
const STOPWORDS = new Set([
  // 묻는 말
  '어디', '어디야', '어디죠', '어디예요', '어디인가요', '몇', '몇개', '얼마', '얼마나',
  '뭐', '뭐야', '무엇', '무슨', '어떤', '어떻게', '언제', '누구', '왜', '어느',
  // 시키는 말·맺는 말
  '알려줘', '알려주세요', '해줘', '해주세요', '주세요', '보여줘', '찾아줘', '찾아주세요',
  '있나요', '있어', '있어요', '되나요', '돼요', '될까요', '인가요', '입니까', '입니다',
  '건가요', '거야', '이야', '예요', '에요', '까요', '나요',
  // 군더더기
  '좀', '진짜', '그냥', '혹시', '관련', '정보', '문의', '내용', '경우', '이거', '저거', '그거',
])

/** 질의를 조건 목록으로 쪼갠다. 각 조건은 AND 로 걸리고, 조건 안의 표기들은 OR 다. */
export function parseQuery(q: string): { raw: string; forms: string[] }[] {
  return normalize(q)
    .split(/\s+/)
    .filter((t) => t && !isStop(t))
    .map((raw) => ({ raw, forms: expandToken(raw) }))
}

/* 묻는 말은 활용형이 끝없다("어디로"·"어디서"·"어디에서"). 앞머리로 본다.
 * 이 목록에 없는 말은 **실제로 0건인지 보고** 빼므로(app/search/page.tsx) 여기는 최소로 둔다. */
const STOPWORD_HEAD = /^(어디|무엇|뭐|얼마|몇|어떻|어떤|언제|누구|무슨|어느)/
/* 맺는 말도 마찬가지다("하나요"·"할까요"). 이것들은 조사 떼기로 '하나' 같은 조각이 되어
 * 엉뚱한 데 걸리므로 **0건 판정에도 안 잡힌다** — 그래서 여기서 미리 뺀다. */
const STOPWORD_TAIL = /(하나요|하시나요|합니까|해요|할까요|될까요|되나요|인가요|이에요|예요|입니다|해줘|해주세요|알려줘|주세요|하죠|하지요)$/

function isStop(t: string): boolean {
  return STOPWORDS.has(t) || STOPWORD_HEAD.test(t) || STOPWORD_TAIL.test(t)
}

/** 조건에서 빼 버린 말 — 화면이 "이건 무시했습니다"라고 밝히는 데 쓴다. */
export function ignoredWords(q: string): string[] {
  return normalize(q).split(/\s+/).filter((t) => t && isStop(t))
}

export type Condition = { raw: string; forms: string[] }

/** 한 항목이 그 조건을 만족하는가 — 표기 중 하나라도 키워드에 있으면 참 */
export function hits(kw: string, c: Condition): boolean {
  for (const f of c.forms) if (kw.includes(f)) return true
  return false
}
