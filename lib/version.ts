/*
 * 앱 버전 — 화면에 띄우는 값 (2026-08-15 사용자 요청)
 *
 * *"어플리케이션 이름 옆에 버전 표시해주세요 업데이트되었는지 안되어있는지 확인겸
 * 얼마나 고도화했는지 보고싶습니다"*
 *
 * 답해야 하는 질문이 둘이라 표시도 둘이다:
 *  ① **내 폰이 최신인가** — 매장 기기는 서비스워커가 캐시를 들고 있어 "배포했는데
 *     화면이 그대로"가 실제로 여러 번 있었다. 화면의 숫자와 방금 올린 숫자가 같으면
 *     반영된 것이고, 낮으면 아직 옛 캐시다. 그래서 **`sw.js` 의 `CACHE_VERSION` 과
 *     같은 숫자**를 쓴다 — 그 값이 곧 "이 기기가 들고 있는 판"이기 때문이다.
 *  ② **얼마나 고도화됐나** — 그 숫자가 배포 덩어리마다 하나씩 오른다.
 *
 * **`CACHE_VERSION` 을 올리면 여기도 함께 올릴 것.** 손으로 두 번 적는 값이라
 * 어긋나면 화면이 거짓말을 하므로, `test-consistency.mjs` 가 둘을 대조한다.
 * (`sw.js` 는 정적 파일로 그대로 서빙돼야 해서 이 모듈을 import 할 수 없다 —
 *  그래서 한쪽에서 읽어 오는 대신 검사로 묶었다.)
 */
export const APP_VERSION = 'v104'

/*
 * 어느 커밋이 올라갔는지 — Vercel 이 빌드할 때 넣어 준다(시스템 환경변수 자동 노출).
 * 로컬 빌드에는 없으므로 없으면 표시하지 않는다. 화면을 채우자고 가짜를 만들지 않는다.
 */
export const BUILD_SHA = (process.env.NEXT_PUBLIC_VERCEL_GIT_COMMIT_SHA || '').slice(0, 7)

/** 이름 옆에 붙일 짧은 표기. 커밋을 알면 함께 적는다. */
export function versionLabel(): string {
  return BUILD_SHA ? `${APP_VERSION} · ${BUILD_SHA}` : APP_VERSION
}
